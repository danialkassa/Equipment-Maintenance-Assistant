SOP-01 液压油更换规程（装备型号：JX-2000A，版本 v1.0）

1. 装备停放在水平地面，铲斗或工作装置落地，发动机熄火并泄压。
2. 待油温降至 40 摄氏度以下，在油箱下放接油盘。
3. 打开油箱底部放油螺塞，排空旧油。
4. 拆卸并清洗油箱，更换吸油滤芯和回油滤芯。
5. 拧紧放油螺塞，从加注口加注 L-HM 46 液压油至液位计上限。
6. 怠速排气：启动发动机，低速动作各执行机构 5 分钟排出系统空气。
7. 检查液位并补加，确认各接头无渗漏。
EOF


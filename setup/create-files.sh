cat > manuals/manual-03.txt <<'EOF'
JX-2000A 液压压力不足诊断手册（版本 v2.1）

症状：动作无力，系统压力表读数低于 14 MPa。
可能原因：
1. 溢流阀调节弹簧疲劳或调压过低；
2. 液压泵磨损造成内泄，泵出口流量下降；
3. 液压缸密封损坏导致内漏；
4. 吸油滤芯堵塞造成泵供油不足。
诊断步骤：先用压力表测量泵出口压力，再测量溢流阀后端压力。
溢流阀调节方法：松开锁紧螺母，顺时针旋转调压螺钉提高压力，每次旋转四分之一圈后试压，
直到系统压力稳定在 16 MPa，然后锁紧螺母。
EOF


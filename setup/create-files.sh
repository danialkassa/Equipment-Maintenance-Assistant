SOP-02 传感器校准规程（适用全部型号，版本 v1.0）

1. 装备水平停放，通电预热 5 分钟。
2. 进入控制面板：菜单 → 维护 → 传感器校准。
3. 选择传感器类型（压力传感器 / 温度传感器 / 振动传感器）。
4. 零点校准：在无压力、环境温度下确认零点。
5. 满量程校准：输入标准压力或温度值，确认满量程输出。
6. 系统更新零偏参数并显示“校准成功”。
7. 若提示零偏超限，检查接线和传感器安装后重试。
